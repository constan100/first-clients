async function toPPTX(p, L, file) {
  const PptxGenJS = load('pptxgenjs');
  if (!PptxGenJS) throw new Error('missing module "pptxgenjs"');
  const pptx = new PptxGenJS();
  pptx.layout = 'LAYOUT_WIDE'; // 13.33 x 7.5 in
  pptx.title = L.planFor(p.product);
  const FONT = 'Calibri';
  const W = 13.33;
  const header = (slide, title, kicker) => {
    slide.background = { color: COLORS.white };
    slide.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: W, h: 0.12, fill: { color: COLORS.accent }, line: { color: COLORS.accent } });
    if (kicker) slide.addText(kicker, { x: 0.6, y: 0.35, w: W - 1.2, h: 0.35, fontFace: FONT, fontSize: 13, color: COLORS.accent, bold: true });
    slide.addText(title, { x: 0.6, y: kicker ? 0.68 : 0.45, w: W - 1.2, h: 0.75, fontFace: FONT, fontSize: 28, bold: true, color: COLORS.ink, fit: 'shrink' });
    slide.addText(str(p.product), { x: 0.6, y: 7.0, w: 6, h: 0.3, fontFace: FONT, fontSize: 10, color: COLORS.muted });
  };
  const bullets = (slide, items, y = 1.7, h = 5.1, size = 20) => {
    if (!items.length) return;
    slide.addText(items.map((t) => ({ text: t, options: { bullet: true, breakLine: true } })), { x: 0.7, y, w: W - 1.4, h, fontFace: FONT, fontSize: size, color: COLORS.ink, valign: 'top', paraSpaceAfter: 10, fit: 'shrink' });
  };
  const table = (slide, head, rows, colW, y = 1.65) => {
    const hdr = head.map((t) => ({ text: t, options: { bold: true, color: COLORS.white, fill: { color: COLORS.accent } } }));
    slide.addTable([hdr, ...rows.map((r) => r.map((c) => ({ text: str(c) })))], {
      x: 0.6, y, w: W - 1.2, colW, fontFace: FONT, fontSize: 12, color: COLORS.ink, border: { type: 'solid', pt: 0.5, color: COLORS.line },
      valign: 'top', autoPage: true, autoPageRepeatHeader: true, autoPageSlideStartY: 1.0, margin: 0.06,
    });
  };
  const g = p.goal || {};
  const f = p.founder || {};

  // 1. Title
  let s = pptx.addSlide();
  s.background = { color: COLORS.accent };
  s.addText(L.planFor(p.product), { x: 0.8, y: 2.2, w: W - 1.6, h: 1.2, fontFace: FONT, fontSize: 40, bold: true, color: COLORS.white, fit: 'shrink' });
  s.addText(str(p.one_liner || p.bet), { x: 0.8, y: 3.5, w: W - 1.6, h: 1.2, fontFace: FONT, fontSize: 20, color: 'E0E7FF', fit: 'shrink' });
  const span = p.weeks[0] && p.weeks[0].start ? `${p.weeks[0].start} → ${p.weeks[p.weeks.length - 1].end || ''}` : str(p.created);
  s.addText(span, { x: 0.8, y: 5.2, w: 8, h: 0.4, fontFace: FONT, fontSize: 14, color: 'E0E7FF' });

  // 2. Bet & goal
  s = pptx.addSlide();
  header(s, L.bet, L.summary);
  s.addText(str(p.bet), { x: 0.6, y: 1.6, w: W - 1.2, h: 1.3, fontFace: FONT, fontSize: 22, color: COLORS.ink, fit: 'shrink', valign: 'top' });
  const cards = [[L.day30, g.day30], [L.horizon90, goal90(g, L)], [L.threshold, g.threshold], [L.northStar, g.north_star], [L.time, `${str(f.hours_per_week)}${f.hours_per_week ? ' ' + L.hoursWeek : ''}${f.budget ? ' · ' + f.budget : ''}`]].filter((c) => c[1]);
  const cw = (W - 1.2 - 0.3 * (cards.length - 1)) / Math.max(cards.length, 1);
  cards.forEach((c, i) => {
    const x = 0.6 + i * (cw + 0.3);
    s.addShape(pptx.ShapeType.roundRect, { x, y: 3.3, w: cw, h: 2.6, fill: { color: COLORS.soft }, line: { color: COLORS.soft }, rectRadius: 0.1 });
    s.addText(c[0], { x: x + 0.2, y: 3.45, w: cw - 0.4, h: 0.4, fontFace: FONT, fontSize: 13, bold: true, color: COLORS.accent });
    s.addText(str(c[1]), { x: x + 0.2, y: 3.9, w: cw - 0.4, h: 1.9, fontFace: FONT, fontSize: 16, color: COLORS.ink, valign: 'top', fit: 'shrink' });
  });

  // 3. This week
  s = pptx.addSlide();
  header(s, L.thisWeek, p.weeks[0] ? weekDates(p.weeks[0]) : '');
  bullets(s, topThree(p).map((a, i) => `${i + 1}. ${a.action}${a.hours ? `  (${a.hours}h)` : ''}`), 1.7, 5, 24);

  // 4. Blockers
  if (arr(p.blockers).length) {
    s = pptx.addSlide();
    header(s, L.blockers);
    table(s, [L.blocker, L.fix, L.hours], p.blockers.map((b) => [b.blocker, b.fix, b.hours]), [4.8, 6.3, 1.03]);
  }
  // 5. Channels
  const chosen = arr(p.channels).filter((c) => c.role !== 'dropped');
  if (chosen.length) {
    s = pptx.addSlide();
    header(s, L.channels);
    table(s, [L.channel, L.role, L.why], chosen.map((c) => [c.name, c.role, c.why]), [3.2, 1.8, 7.13]);
  }
  // 6. Weeks
  arr(p.weeks).forEach((w, i) => {
    s = pptx.addSlide();
    header(s, `${L.weekN(w.week || i + 1)}${w.theme ? ` — ${w.theme}` : ''}`, weekDates(w));
    table(s, [L.action, L.channel, L.hours, L.doneWhen], arr(w.actions).map((a) => [`${a.top3 ? '★ ' : ''}${a.action}`, a.channel, a.hours, a.done_when]), [5.6, 2.0, 0.9, 3.63]);
  });
  // 6b. Checklists
  arr(p.checklists).forEach((c) => {
    s = pptx.addSlide();
    header(s, str(c.title || L.checklists));
    table(s, ['', L.when, L.item], arr(c.items).map((it) => [it.status === 'done' ? '☑' : '☐', it.when, it.item]), [0.6, 2.2, 9.33]);
  });
  // 7. If/then
  if (arr(p.if_then).length) {
    s = pptx.addSlide();
    header(s, L.ifThen);
    table(s, [L.if, L.then], p.if_then.map((r) => [r.if, r.then]), [5.2, 6.93]);
  }
  // 8. Metrics & review
  s = pptx.addSlide();
  header(s, L.metrics);
  const r = p.review || {};
  bullets(s, [...arr(p.metrics).map((m) => `${m.name}${m.type === 'north_star' ? ` — ${L.northStar}` : ''}${m.source ? ` (${m.source})` : ''}`), L.reviewText(r.day || 'Sunday', r.minutes || 15)], 1.7, 5, 18);

  await pptx.writeFile({ fileName: file });
}

// ---------- Word ----------
async function toDOCX(p, L, file) {
  const d = load('docx');
  if (!d) throw new Error('missing module "docx"');
  const { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, WidthType, ShadingType, ExternalHyperlink } = d;
  const P = (text, opts = {}) => new Paragraph({ children: [new TextRun({ text: str(text), ...opts })], spacing: { after: 100 } });
  const LV = (label, value) => new Paragraph({ children: [new TextRun({ text: `${label}: `, bold: true }), new TextRun(str(value))], spacing: { after: 80 } });
  const H = (text, level = HeadingLevel.HEADING_2) => new Paragraph({ text: str(text), heading: level, spacing: { before: 240, after: 120 } });
  const check = (a, text) => new Paragraph({ children: [new TextRun({ text: (a.status === 'done' ? '☑ ' : '☐ ') }), new TextRun(str(text))], spacing: { after: 60 } });
  const table = (head, rows, widths) => new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({ tableHeader: true, children: head.map((h, i) => new TableCell({ width: widths ? { size: widths[i], type: WidthType.PERCENTAGE } : undefined, shading: { type: ShadingType.CLEAR, color: 'auto', fill: COLORS.soft }, children: [new Paragraph({ children: [new TextRun({ text: str(h), bold: true })] })] })) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) => new TableCell({ width: widths ? { size: widths[i], type: WidthType.PERCENTAGE } : undefined, children: [new Paragraph(str(c))] })) })),
    ],
  });
  const g = p.goal || {};
  const f = p.founder || {};
  const kids = [];
  kids.push(new Paragraph({ text: L.planFor(p.product), heading: HeadingLevel.TITLE }));
  if (p.created) kids.push(P(p.created, { color: COLORS.muted }));
  kids.push(LV(L.bet, p.bet));
  if (p.one_liner) kids.push(LV(L.oneLiner, p.one_liner));
  if (g.day30) kids.push(LV(L.day30, g.day30));
  if (g.target90 || g.floor90) kids.push(LV(L.horizon90, goal90(g, L)));
  if (g.threshold) kids.push(LV(L.threshold, g.threshold));
  if (g.north_star) kids.push(LV(L.northStar, g.north_star));
  if (f.hours_per_week || f.budget) kids.push(LV(L.time, `${str(f.hours_per_week)}${f.hours_per_week ? ' ' + L.hoursWeek : ''}${f.budget ? ' · ' + L.budget + ' ' + f.budget : ''}`));
  kids.push(H(L.thisWeek));
  topThree(p).forEach((a, i) => kids.push(check(a, `${i + 1}. ${a.action}${a.hours ? ` (${a.hours}h)` : ''}${a.asset ? ` — ${a.asset}` : ''}`)));
  if (arr(p.blockers).length) { kids.push(H(L.blockers)); kids.push(table([L.blocker, L.fix, L.hours, L.status], p.blockers.map((b) => [b.blocker, b.fix, b.hours, b.status || 'todo']), [38, 44, 8, 10])); }
  arr(p.weeks).forEach((w, i) => {
    kids.push(H(`${L.weekN(w.week || i + 1)}${weekDates(w) ? ` (${weekDates(w)})` : ''}${w.theme ? ` — ${w.theme}` : ''}`));
    kids.push(table(['', L.action, L.channel, L.hours, L.doneWhen], arr(w.actions).map((a) => [a.status === 'done' ? '☑' : '☐', `${a.top3 ? '★ ' : ''}${a.action}`, a.channel, a.hours, a.done_when]), [5, 45, 16, 8, 26]));
  });
  if (arr(p.results).length && arr(p.metrics).length) { kids.push(H(L.weeklyNumbers)); kids.push(table([L.date, ...p.metrics.map((m) => m.name)], p.results.map((r) => [r.date, ...p.metrics.map((m) => r.values && r.values[m.name])]))); }
  arr(p.checklists).forEach((c) => { kids.push(H(c.title || L.checklists)); kids.push(table(['', L.when, L.item, L.value], arr(c.items).map((it) => [it.status === 'done' ? '☑' : '☐', it.when, it.item, it.value]), [5, 18, 57, 20])); });
  if (arr(p.if_then).length) { kids.push(H(L.ifThen)); kids.push(table([L.if, L.then], p.if_then.map((r) => [r.if, r.then]), [45, 55])); }
  if (arr(p.channels).length) { kids.push(H(L.channels)); kids.push(table([L.channel, L.role, L.why], p.channels.map((c) => [c.name, c.role, c.why]), [25, 15, 60])); }
  if (arr(p.metrics).length) { kids.push(H(L.metrics)); kids.push(table([L.metric, L.type, L.source, L.baseline], p.metrics.map((m) => [m.name, m.type, m.source, m.baseline]), [30, 15, 40, 15])); }
  const r = p.review || {};
  kids.push(H(L.review)); kids.push(P(L.reviewText(r.day || 'Sunday', r.minutes || 15)));
  if (arr(p.sources).length) {
    kids.push(H(L.sources));
    p.sources.forEach((s) => kids.push(new Paragraph({ bullet: { level: 0 }, children: s.url ? [new ExternalHyperlink({ link: s.url, children: [new TextRun({ text: str(s.title || s.url), style: 'Hyperlink' })] })] : [new TextRun(str(s.title))] })));
  }
  kids.push(P(L.generated, { italics: true, color: COLORS.muted }));
  const doc = new Document({ creator: 'first-clients', title: L.planFor(p.product), styles: { default: { document: { run: { font: 'Calibri', size: 22 } } } }, sections: [{ children: kids }] });
  fs.writeFileSync(file, await Packer.toBuffer(doc));
}

// ---------- PDF ----------
function findSoffice() {
  const candidates = ['soffice', 'libreoffice', 'C:\\Program Files\\LibreOffice\\program\\soffice.exe', '/Applications/LibreOffice.app/Contents/MacOS/soffice'];
  for (const c of candidates) {
    try { execFileSync(c, ['--version'], { stdio: 'ignore', timeout: 20000 }); return c; } catch (e) { /* next */ }
  }
  return null;
}

// ---------- main ----------
async function main() {
  const args = process.argv.slice(2);
  const opt = { formats: 'xlsx,pptx,docx,md', out: null, check: false, input: null };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--formats') opt.formats = args[++i];
    else if (args[i] === '--out') opt.out = args[++i];
    else if (args[i] === '--check') opt.check = true;
    else if (args[i] === '-h' || args[i] === '--help') { console.log(fs.readFileSync(__filename, 'utf8').split('*/')[0]); return; }
    else opt.input = args[i];
  }
  if (!opt.input) { console.error('Usage: node export.cjs <plan-data.json> [--formats xlsx,pptx,docx,md,html,csv,pdf|all] [--out <dir>]'); process.exit(2); }
  let plan;
  try { plan = JSON.parse(fs.readFileSync(opt.input, 'utf8').replace(/^\ufeff/, '')); } catch (e) { console.error(`Cannot read ${opt.input}: ${e.message}`); process.exit(2); }
  const { errors, warnings } = validate(plan);
  warnings.forEach((w) => console.log(`warning: ${w}`));
  if (errors.length) { errors.forEach((e) => console.error(`error: ${e}`)); process.exit(1); }
  if (opt.check) { console.log('plan-data.json is valid.'); return; }

  const lang = str(plan.language).slice(0, 2).toLowerCase();
  const L = { ...(LABELS[lang] || LABELS.en), ...(plan.labels || {}) };
  const formats = opt.formats === 'all' ? ['xlsx', 'pptx', 'docx', 'md', 'html', 'csv', 'pdf'] : opt.formats.split(',').map((s) => s.trim().toLowerCase()).filter(Boolean);
  const out = opt.out || path.join(path.dirname(path.resolve(opt.input)), 'exports');
  fs.mkdirSync(out, { recursive: true });
  const base = path.join(out, `${slug(plan.product)}-plan`);
  const done = [];
  const failed = [];
  const missing = new Set();
  const run = async (fmt, fn) => {
    try { const f = await fn(); done.push(f); } catch (e) {
      failed.push(`${fmt}: ${e.message}`);
      const m = /missing module "([^"]+)"/.exec(e.message); if (m) missing.add(m[1]);
    }
  };
  for (const fmt of formats) {
    if (fmt === 'md') await run(fmt, () => { fs.writeFileSync(base + '.md', toMarkdown(plan, L)); return base + '.md'; });
    else if (fmt === 'html') await run(fmt, () => { fs.writeFileSync(base + '.html', toHTML(plan, L)); return base + '.html'; });
    else if (fmt === 'csv') await run(fmt, () => { fs.writeFileSync(base + '-tasks.csv', toCSV(plan, L)); return base + '-tasks.csv'; });
    else if (fmt === 'xlsx') await run(fmt, async () => { await toXLSX(plan, L, base + '.xlsx'); return base + '.xlsx'; });
    else if (fmt === 'pptx') await run(fmt, async () => { await toPPTX(plan, L, base + '.pptx'); return base + '.pptx'; });
    else if (fmt === 'docx') await run(fmt, async () => { await toDOCX(plan, L, base + '.docx'); return base + '.docx'; });
    else if (fmt === 'pdf') await run(fmt, async () => {
      const soffice = findSoffice();
      if (soffice) {
        if (!fs.existsSync(base + '.docx')) await toDOCX(plan, L, base + '.docx');
        execFileSync(soffice, ['--headless', '--convert-to', 'pdf', '--outdir', out, base + '.docx'], { stdio: 'ignore', timeout: 120000 });
        if (fs.existsSync(base + '.pdf')) return base + '.pdf';
      }
      fs.writeFileSync(base + '-print.html', toHTML(plan, L));
      console.log('note: LibreOffice not found, so no direct PDF. Open the -print.html file in a browser and use Print > Save as PDF (or use your platform\'s PDF tool).');
      return base + '-print.html';
    });
    else failed.push(`${fmt}: unknown format (use xlsx, pptx, docx, md, html, csv, pdf)`);
  }
  done.forEach((f) => console.log(`wrote ${f}`));
  failed.forEach((f) => console.error(`failed ${f}`));
  if (missing.size) {
    console.error(`\nInstall the missing libraries once, then re-run:\n  npm install --no-save --prefix "<some-dir>" ${['docx@9.15.3', 'pptxgenjs@4.0.1', 'exceljs@4.4.0'].filter((x) => missing.has(x.split('@')[0])).join(' ')}\n  set FC_EXPORT_MODULES to "<some-dir>/node_modules"`);
  }
  process.exit(failed.length ? 1 : 0);
}

