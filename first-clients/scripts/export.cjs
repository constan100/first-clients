// ---------- module loading ----------
function load(name) {
  const paths = [__dirname, process.cwd()];
  if (process.env.FC_EXPORT_MODULES) paths.unshift(path.dirname(process.env.FC_EXPORT_MODULES), process.env.FC_EXPORT_MODULES);
  try {
    return require(require.resolve(name, { paths }));
  } catch (e) {
    return null;
  }
}

